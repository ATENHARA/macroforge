"""Generate the Lua data file that the in-game addon loads."""
from __future__ import annotations

_ESCAPES = {"\\": "\\\\", '"': '\\"', "\n": "\\n", "\r": "\\r", "\t": "\\t"}


def lua_str(text: str) -> str:
    """Return ``text`` as a double-quoted Lua string literal.

    Backslash, quote and every control character are escaped (as ``\\ddd`` when there is no short
    form), so no input can end the literal early.
    """
    out = []
    for ch in text:
        if ch in _ESCAPES:
            out.append(_ESCAPES[ch])
        elif ord(ch) < 32 or ord(ch) == 127:
            out.append(f"\\{ord(ch):03d}")
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


def lua_list(entries: list[dict], indent: str = "    ") -> str:
    """One ``{ name = ..., icon = ..., body = ... },`` row per macro (plus ``script = true``)."""
    return "\n".join(
        f'{indent}{{ name = {lua_str(m["name"])}, icon = {int(m["icon"])}, '
        f'body = {lua_str(m["body"])}{", script = true" if m.get("script") else ""} }},'
        for m in entries)


def lua_replies(replies: list[dict]) -> str:
    """The last few agent replies, shipped to the game inside the data and slot files."""
    return "\n".join(
        f'    {{ id = {int(r["id"])}, req = {int(r.get("req", 0))}, '
        f'text = {lua_str(str(r["text"]))}{", pending = true" if r.get("pending") else ""} }},'
        for r in replies[-5:])


def _names(names: list[str]) -> str:
    return ", ".join(lua_str(n) for n in names)


def render_data(spec: dict, rev: int, replies: list[dict]) -> str:
    """Render ``MacroForgeData.lua`` for a resolved spec (see ``spec.resolve_spec``)."""
    chars = "\n".join(
        f'    [{lua_str(c)}] = {{\n{lua_list(entries, "        ")}\n    }},'
        for c, entries in spec["chars"].items())
    remove = spec["remove"]
    remove_chars = "\n".join(
        f"      [{lua_str(c)}] = {{ {_names(names)} }}," for c, names in remove["chars"].items())
    return ("-- GENERATED by macroforge.py - do not edit\n"
            "MacroForgeData = {\n"
            f"  rev = {int(rev)},\n"
            f"  account = {{\n{lua_list(spec['account'])}\n  }},\n"
            f"  chars = {{\n{chars}\n  }},\n"
            f"  remove = {{\n    account = {{ {_names(remove['account'])} }},\n"
            f"    chars = {{\n{remove_chars}\n    }},\n  }},\n"
            f"  replies = {{\n{lua_replies(replies)}\n  }},\n}}\n")
